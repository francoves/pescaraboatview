import puppeteer from "puppeteer-core";
import fs from "node:fs";
const EXE="C:/Program Files/Google/Chrome/Application/chrome.exe";
const OUT="C:/Users/Franco/Documents/Code/christian-de-leonibus/_study"; fs.mkdirSync(OUT,{recursive:true});
const b=await puppeteer.launch({executablePath:EXE,headless:"new",args:["--no-sandbox"]});
const p=await b.newPage(); await p.setViewport({width:1380,height:900,deviceScaleFactor:1.1});
await p.goto("http://localhost:8080/proto.html",{waitUntil:"networkidle2",timeout:60000});
await new Promise(r=>setTimeout(r,1000));
await p.screenshot({path:`${OUT}/proto.png`,fullPage:true});
await p.close();
const m=await b.newPage(); await m.setViewport({width:390,height:844,deviceScaleFactor:1.4});
await m.goto("http://localhost:8080/proto.html",{waitUntil:"networkidle2",timeout:60000});
await new Promise(r=>setTimeout(r,800));
await m.screenshot({path:`${OUT}/proto-m.png`,fullPage:true});
await b.close(); console.log("done");
